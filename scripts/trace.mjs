#!/usr/bin/env node
/**
 * Silhouette tracing pipeline.
 *
 *   source image (SVG / PNG / JPG / WebP)
 *     → sharp: resize, flatten on white, grayscale, hard threshold
 *     → potrace: bitmap → Bézier outline
 *     → normalise: round coordinates, crop viewBox, count anchors
 *     → src/data/silhouette.ts (typed module consumed by the hero)
 *
 * Usage:
 *   pnpm trace                       # traces scripts/source/silhouette.svg
 *   pnpm trace path/to/portrait.png  # traces your own high-contrast cut-out
 *   node scripts/trace.mjs --if-changed
 *       Re-traces only when the source image differs from the one recorded in
 *       src/data/silhouette.ts. `pnpm dev` and `pnpm build` run this, so
 *       replacing the source artwork can never leave a stale silhouette.
 *
 * Tips for a photo: remove the background first so the subject is dark on white
 * (or transparent). Tweak THRESHOLD if the outline loses detail.
 */
import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const args = process.argv.slice(2)
const ifChanged = args.includes('--if-changed')
const inputArg = args.find((a) => !a.startsWith('--'))
const output = path.join(root, 'src/data/silhouette.ts')
const previous = await readFile(output, 'utf8').catch(() => '')

// Without an explicit path, --if-changed re-checks whichever source was traced last.
const recorded = /^\/\/ Source: (.+?) · /m.exec(previous)?.[1]
const input = inputArg
  ? path.resolve(process.cwd(), inputArg)
  : path.join(root, ifChanged && recorded ? recorded : 'scripts/source/silhouette.svg')

const sourceHash = createHash('sha1')
  .update(await readFile(input))
  .digest('hex')
  .slice(0, 16)
if (ifChanged && previous.includes(`// Source hash: ${sourceHash}`)) {
  console.log(`› silhouette up to date (${path.relative(root, input)})`)
  process.exit(0)
}

// Heavy native deps load only when a trace is actually needed.
const { default: sharp } = await import('sharp')
const { default: potrace } = await import('potrace')

const HEIGHT = 900
const THRESHOLD = 140
const ANCHOR_SAMPLES = 28

console.log(`› tracing ${path.relative(root, input)}`)

const bitmap = await sharp(input, { density: 220 })
  .resize({ height: HEIGHT, fit: 'inside' })
  .flatten({ background: '#ffffff' })
  .grayscale()
  .threshold(THRESHOLD)
  .png()
  .toBuffer()

const svg = await new Promise((resolve, reject) => {
  potrace.trace(
    bitmap,
    { threshold: THRESHOLD, turdSize: 40, optTolerance: 0.3, alphaMax: 1, color: '#000000' },
    (err, result) => (err ? reject(err) : resolve(result)),
  )
})

const raw = /\sd="([^"]+)"/.exec(svg)?.[1]
if (!raw) throw new Error('potrace returned no path data')

// ── Normalise: tokenise, round to one decimal, collect anchors + bounds ──────
const tokens = raw.match(/[MLCZmlcz]|-?\d*\.?\d+(?:e[-+]?\d+)?/g) ?? []
const round = (n) => Math.round(n * 10) / 10
const anchors = []
let minX = Infinity
let minY = Infinity
let maxX = -Infinity
let maxY = -Infinity
const out = []
let cmd = ''
const buf = []

const flushPairs = () => {
  // Emits every complete segment currently buffered for the active command.
  const per = cmd === 'C' ? 6 : 2
  while (buf.length >= per) {
    const seg = buf.splice(0, per)
    for (let i = 0; i < seg.length; i += 2) {
      minX = Math.min(minX, seg[i])
      minY = Math.min(minY, seg[i + 1])
      maxX = Math.max(maxX, seg[i])
      maxY = Math.max(maxY, seg[i + 1])
    }
    anchors.push([seg[per - 2], seg[per - 1]])
    out.push(seg.map(round).join(' '))
  }
}

for (const t of tokens) {
  if (/^[MLCZ]$/i.test(t)) {
    flushPairs()
    cmd = t.toUpperCase()
    if (t !== cmd) throw new Error('relative commands are not expected from potrace')
    out.push(cmd)
  } else {
    buf.push(Number(t))
    flushPairs()
  }
}
flushPairs()

const d = out.join(' ').replace(/ Z/g, 'Z').replace(/\s+/g, ' ').trim()
const pad = 6
const vb = [round(minX - pad), round(minY - pad), round(maxX - minX + pad * 2), round(maxY - minY + pad * 2)]
const step = Math.max(1, Math.floor(anchors.length / ANCHOR_SAMPLES))
const sampled = anchors
  .filter((_, i) => i % step === 0)
  .slice(0, ANCHOR_SAMPLES)
  .map(([x, y]) => [round(x), round(y)])
const subpaths = (d.match(/M/g) ?? []).length

const file = `// AUTO-GENERATED by scripts/trace.mjs — do not edit by hand.
// Source: ${path.relative(root, input)} · ${new Date().toISOString().slice(0, 10)}
// Source hash: ${sourceHash}
// Regenerate with \`pnpm trace\` (see README → "Regenerate the silhouette").

export interface Silhouette {
  /** SVG viewBox cropped to the traced outline. */
  viewBox: string
  width: number
  height: number
  /** Potrace outline (absolute M / L / C commands). */
  d: string
  /** Number of vector anchor points in the outline. */
  points: number
  /** Number of closed sub-paths (outer contours + holes). */
  subpaths: number
  /** A sample of anchor points used for the pen-tool markers. */
  anchors: ReadonlyArray<readonly [number, number]>
}

export const silhouette: Silhouette = {
  viewBox: '${vb.join(' ')}',
  width: ${vb[2]},
  height: ${vb[3]},
  d: '${d}',
  points: ${anchors.length},
  subpaths: ${subpaths},
  anchors: ${JSON.stringify(sampled)},
}
`

await writeFile(output, file)
console.log(
  `✓ wrote ${path.relative(root, output)} — ${anchors.length} anchors, ${subpaths} sub-paths, ${(d.length / 1024).toFixed(1)} KB path data`,
)
